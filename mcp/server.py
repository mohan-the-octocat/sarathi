def handle_initialize(req_id: Any, params: dict[str, Any]) -> dict[str, Any]:
  """Handles MCP initialize handshake."""
  return {
      "jsonrpc": "2.0",
      "id": req_id,
      "result": {
          "protocolVersion": PROTOCOL_VERSION,
          "capabilities": {
              "tools": {
                  "listChanged": False,
              },
          },
          "serverInfo": {
              "name": SERVER_NAME,
              "version": SERVER_VERSION,
          },
      },
  }


def handle_tools_list(req_id: Any) -> dict[str, Any]:
  """Returns list of available tools and schemas."""
  return {
      "jsonrpc": "2.0",
      "id": req_id,
      "result": {
          "tools": TOOLS,
      },
  }


def handle_tools_call(req_id: Any, params: dict[str, Any]) -> dict[str, Any]:
  """Executes requested tool and returns JSON-RPC formatted result."""
  name = params.get("name", "")
  args = params.get("arguments", {})

  try:
    if name == "detect_test_tampering":
      result = detect_test_tampering(
          workspace_dir=args.get("workspace_dir", "."),
          base_revision=args.get("base_revision"),
      )
    elif name == "verify_receipts":
      result = verify_receipts(
          receipt_path=args.get("receipt_path", ""),
      )
    elif name == "get_orchestration_status":
      result = get_context_status(
          conversation_id=args.get("conversation_id"),
          context_tokens=args.get("context_tokens"),
      )
    elif name == "record_orchestration_event":
      result = record_orchestration_event(
          task_tier=args.get("task_tier", "tier_2_standard"),
          verification_outcome=args.get("verification_outcome", "NOT_APPLICABLE"),
          conductor_model=args.get("conductor_model", "auto"),
          subagents_spawned=args.get("subagents_spawned", 0),
          subagent_calls_offloaded=args.get("subagent_calls_offloaded", 0),
          test_violations_count=args.get("test_violations_count", 0),
          duration_seconds=args.get("duration_seconds", 0.0),
          details=args.get("details", ""),
          session_id=args.get("session_id", ""),
      )
    else:
      return {
          "jsonrpc": "2.0",
          "id": req_id,
          "error": {
              "code": -32601,
              "message": f"Tool not found: {name}",
          },
      }

    return {
        "jsonrpc": "2.0",
        "id": req_id,
        "result": {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps(result, indent=2),
                }
            ],
            "isError": False,
        },
    }

  except Exception as e:
    logging.exception(f"Error handling tool call {name}")
    return {
        "jsonrpc": "2.0",
        "id": req_id,
        "result": {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps({"error": str(e)}, indent=2),
                }
            ],
            "isError": True,
        },
    }


def main() -> int:
  """Main loop reading JSON-RPC over stdin/stdout."""
  logging.info(f"Starting {SERVER_NAME} v{SERVER_VERSION} (stdio mode)...")

  for raw_line in sys.stdin:
    line = raw_line.strip()
    if not line:
      continue

    try:
      msg = json.loads(line)
    except json.JSONDecodeError as e:
      logging.error(f"Malformed JSON received: {e}")
      continue

    req_id = msg.get("id")
    method = msg.get("method")
    params = msg.get("params", {})

    if method == "initialize":
      resp = handle_initialize(req_id, params)
    elif method == "notifications/initialized":
      continue
    elif method == "ping":
      resp = {"jsonrpc": "2.0", "id": req_id, "result": {}}
    elif method == "tools/list":
      resp = handle_tools_list(req_id)
    elif method == "tools/call":
      resp = handle_tools_call(req_id, params)
    else:
      if req_id is not None:
        resp = {
            "jsonrpc": "2.0",
            "id": req_id,
            "error": {
                "code": -32601,
                "message": f"Method not supported: {method}",
            },
        }
      else:
        continue

    sys.stdout.write(json.dumps(resp) + "\n")
    sys.stdout.flush()

  return 0


if __name__ == "__main__":
  sys.exit(main())
